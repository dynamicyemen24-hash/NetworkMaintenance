param(
    [string]$Mode = "Full",
    [string]$ConfigPath = "C:\NetworkMaintenance\Config\Config.json",
    [string]$LogPath = "C:\NetworkMaintenance\Logs",
    [switch]$DryRun,
    [switch]$AutoHeal,
    [switch]$Continuous,
    [switch]$Report,
    [switch]$Schedule,
    [string]$Target = ""
)

$Timestamp = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
$LogFile = "$LogPath\Maintenance_$(Get-Date -Format 'yyyyMMdd').log"

function Write-Log {
    param([string]$Message, [string]$Level = "INFO")
    $entry = "[$Timestamp][$Level] $Message"
    Add-Content -Path $LogFile -Value $entry -Force
    switch ($Level) {
        "ERROR" { Write-Host $entry -ForegroundColor Red }
        "WARN" { Write-Host $entry -ForegroundColor Yellow }
        "SUCCESS" { Write-Host $entry -ForegroundColor Green }
        "ACTION" { Write-Host $entry -ForegroundColor Cyan }
        "HEADER" { Write-Host $entry -ForegroundColor Magenta }
        default { Write-Host $entry -ForegroundColor White }
    }
}

function Show-Banner {
    Write-Log "============================================" "HEADER"
    Write-Log "  NetworkMaintenance-Pro v2.0.0" "HEADER"
    Write-Log "  Professional Network Maintenance System" "HEADER"
    Write-Log "============================================" "HEADER"
    Write-Log "Mode: $Mode | Time: $Timestamp" "HEADER"
    Write-Log ""
}

function Run-Diagnostics {
    Write-Log "=== Running Diagnostics ===" "ACTION"
    & "C:\NetworkMaintenance\Scripts\01_Diagnostics.ps1" -ConfigPath $ConfigPath -LogPath $LogPath
    Write-Log "Diagnostics Complete!" "SUCCESS"
}

function Run-Optimization {
    Write-Log "=== Running Optimization ===" "ACTION"
    & "C:\NetworkMaintenance\Scripts\02_Optimization.ps1" -ConfigPath $ConfigPath -LogPath $LogPath -DryRun:$DryRun -ForceApply:(!$DryRun)
    Write-Log "Optimization Complete!" "SUCCESS"
}

function Run-SafeCleaning {
    Write-Log "=== Running Safe Cleaning (SCE Engine) ===" "ACTION"
    $enterpriseConfig = "C:\NetworkMaintenance\Config\EnterpriseConfig.json"
    $sceParams = @{ ConfigPath = $enterpriseConfig; SafetyLevel = "Balanced" }
    if ($DryRun) { $sceParams.DryRun = $true }
    & "C:\NetworkMaintenance\Scripts\Engines\SCE-Engine.ps1" @sceParams
    Write-Log "Safe Cleaning Complete!" "SUCCESS"
}

function Run-AutoHeal {
    Write-Log "=== Running Auto-Heal ===" "ACTION"
    & "C:\NetworkMaintenance\Scripts\03_AutoHeal.ps1" -ConfigPath $ConfigPath -LogPath $LogPath
    Write-Log "Auto-Heal Complete!" "SUCCESS"
}

function Run-Monitoring {
    Write-Log "=== Running Monitoring ===" "ACTION"
    & "C:\NetworkMaintenance\Scripts\04_Monitoring.ps1" -ConfigPath $ConfigPath -LogPath $LogPath -Continuous:$Continuous
    Write-Log "Monitoring Complete!" "SUCCESS"
}

function Generate-Report {
    Write-Log "=== Generating Report ===" "ACTION"
    
    $reportDate = Get-Date -Format "yyyy-MM-dd"
    $reportFile = "$LogPath\Reports\Report_$reportDate.md"
    
    $content = @"
