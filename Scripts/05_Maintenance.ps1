"@

    $content | Set-Content $reportFile -Force
    Write-Log "Report saved to: $reportFile" "SUCCESS"
}

function Get-HealthScore {
    $score = 100
    
    # Check latency
    $pingOutput = cmd /c "ping -n 5 $($Config.Diagnostic.PingTarget)" 2>nul
    $latencies = @()
    foreach ($line in $pingOutput) {
        if ($line -match "time=(\d+)ms") { $latencies += [int]$matches[1] }
    }
    
    if ($latencies.Count -gt 0) {
        $avg = ($latencies | Measure-Object -Average).Average
        if ($avg -gt $Config.Network.CriticalLatencyMs) { $score -= 40 }
        elseif ($avg -gt $Config.Network.WarningLatencyMs) { $score -= 20 }
        elseif ($avg -gt $Config.Network.ExpectedLatencyMs) { $score -= 10 }
    }
    
    # Check DNS
    try {
        Resolve-DnsName "google.com" -Server 1.1.1.1 -QuickTimeout -ErrorAction Stop | Out-Null
    } catch {
        $score -= 30
    }
    
    # Check if optimization applied
    if (Test-Path "C:\NetworkMaintenance\Config\LastOptimization.json") {
        $score += 5
    }
    
    return "Score: $score/100"
}

